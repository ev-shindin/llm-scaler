#!/usr/bin/env python3
"""
two_model_profile.py -- render the inference-perf profiles that drive the
two-model anti-phase run, plus the phase table the report buckets against.

Load is generated by inference-perf, the llm-d benchmark harness's own load
generator, rather than by a bespoke client. That is not a cosmetic choice:

  * The schedule is a first-class object in the harness (`load.stages`), so
    anti-phase is expressed by giving the two models MIRRORED ladders over the
    same boundaries rather than by a loop that has to be trusted to keep time.
  * The harness tokenizes with the model's OWN tokenizer, so `input_tokens`
    means input tokens. A hand-rolled generator that counts words is off by
    whatever the tokenizer does, differently for each of the two models -- and
    this scenario compares two models.
  * It reports its own scheduling delay (`load_summary.schedule_delay`), which
    is exactly the quantity that decides whether the driver, rather than the
    cluster, produced the latency being compared. Self-reported by the thing
    that would be at fault.

One profile per model, written from one schedule so the two cannot drift:
`--emit schedule` prints that schedule as JSON for the report's meta, and
`--emit profile --role a|b` prints the YAML for one side of it.

Phases become STAGES, and every phase a model RISES into is cut in two at
`--rise-window`. inference-perf v0.6.1 reports `time_to_first_token` only as a
per-stage distribution -- its per-request records carry no token timestamps --
so the first 90s of a rise, which is this scenario's headline number, has to BE
a stage or it cannot be measured at all. The cut does not change the load: both
sub-stages run the same rate back to back.

Between consecutive bursts sits an `--overlap` band where BOTH models are at
the low rate. A stage ends when its in-flight requests drain and the bursting
model drains slower, so the two models do not cross a boundary at the same
instant -- measured, a divergence that reached 6.1s and changed sign with the
burst. The band is what keeps that divergence from becoming time when both
models burst at once, which a pool cannot serve and which would be recorded as
the pool failing.

A stage is time-boxed, so both models cross every boundary together as long as
they start together -- which the Job's start barrier, not this file, is
responsible for -- and stay together only to within that drain difference,
which is what the band absorbs.

THE PROMPTS SHARE NO PREFIX, BY DEFAULT. `--data synthetic` slices every prompt
from a random offset into inference-perf's 5 MB corpus, freshly per request, so
no two requests start alike. That is what lets a scale-up be measured at all:
llm-d's shipped scheduling profile weights prefix-cache-scorer highest (3,
against 2 for queue depth and 2 for KV utilisation), and its hashes chain from
the first token -- so a replica that has cached a prompt's opening wins every
later request that shares it, regardless of its queue, and a replica that has
cached nothing never receives one. MEASURED on CoreWeave with the shared_prefix
dataset at 32 groups x 64 prompts (2048 distinct prompts, cycled): per model
the busiest engine held 99.0% and 98.7% of prompt tokens over a whole arm, and
every replica the autoscaler added served 0.3-2.0%. With synthetic, an EMPTY
second replica took 49.4% of 9 rps from its first minute (p50 TTFT 58ms). A
result from the shared_prefix dataset is therefore about one replica per model
whatever the table says; `--data shared_prefix` is kept only to reproduce it.
"""

import argparse
import json
import sys


def build_schedule(phase_seconds, cycles, low_rps, high_rps, lead_in, overlap=0,
                   high_rps_b=None):
    """Anti-phase square wave: A low->high->low..., B high->low->high...

    `overlap` inserts a band between consecutive phases where BOTH models are
    at the low rate, so their bursts cannot run into each other.

    Why that band is needed at all: the two models do not cross a stage
    boundary at the same instant. A stage ends when its in-flight requests
    drain, and the model that is BURSTING drains slower -- measured on
    CoreWeave, per-stage drains of 4-16s and a net divergence that reached
    6.1s and CHANGED SIGN as the burst moved from one model to the other.
    Without a band, that divergence is time when both models are bursting at
    once. A pool asked for two models simultaneously can serve one, so it would
    be recorded as the pool failing at the very thing this scenario measures,
    when it is an artefact of the driver.

    The band costs the flat-sum premise 2*low instead of low+high for its
    duration. That is a dip in total demand, not a rise, and scale-down
    stabilization here is 300s -- so at 30s no replica is given back because of
    it, and what the fleet does is unchanged.

    The lead-in and the phase shape are otherwise identical to the schedule the
    previous bespoke loader built, deliberately: the report's rise windows, the
    meta signature and the runbook's phase table all key on it.
    """
    # The two models do not have the same capacity, so one burst rate cannot
    # exercise both. MEASURED: at 9 rps Llama served comfortably once scaled
    # (steady p50 83ms) while Qwen drowned (steady p50 5717ms); at 6 rps Qwen
    # needed a second replica and showed a real rise penalty while Llama never
    # needed one and its rise window was indistinguishable from steady state.
    #
    # This also serves the premise better rather than worse. The claim is that
    # the SUM OF DEMAND is flat; with equal request rates and unequal capacity
    # the sum of ACCELERATOR demand is not, because one model's 6 rps costs two
    # replicas and the other's costs one.
    if high_rps_b is None:
        high_rps_b = high_rps
    phases = []
    t = 0
    if lead_in > 0:
        # Both models at the LOW rate first. Without it the run starts at the
        # instant of a burst and every arm measures a cold stack rather than a
        # scale-up: the models have never served a request, the pool has never
        # been asked for anything, and the first burst pays a first-request
        # penalty that has nothing to do with the pool.
        phases.append((t, t + lead_in, low_rps, low_rps))
        t += lead_in
    for cycle in range(cycles):
        for first in (True, False):
            if phases and overlap > 0:
                # Not before the very first burst: the lead-in already is a
                # both-low band, and a second one would only add dead time.
                if not (cycle == 0 and first and lead_in > 0):
                    phases.append((t, t + overlap, low_rps, low_rps))
                    t += overlap
            rates = (low_rps, high_rps_b) if first else (high_rps, low_rps)
            phases.append((t, t + phase_seconds) + rates)
            t += phase_seconds
    return phases


def schedule_json(stages):
    """The stage table, which is what the report buckets against.

    Stages, not the coarser phases: these ARE the windows the harness reports
    a TTFT distribution for, so a report keyed on anything else would be
    describing windows nobody measured.
    """
    return [{"start": s, "end": e, "rate_a": ra, "rate_b": rb}
            for s, e, ra, rb in stages]


def stage_map(schedule, rise_window):
    """The STAGES both models run, as (start, end, rate_a, rate_b).

    Every phase after the lead-in is cut in two at `rise_window`: an opening
    sub-stage and the remainder, at the SAME rate, so the load is unchanged.

    Why cut it at all: inference-perf v0.6.1 reports `time_to_first_token` only
    as a per-STAGE distribution -- there are no per-request token timestamps to
    re-cut afterwards. The headline number of this scenario is TTFT in the first
    90s of a rise, so that window has to BE a stage or it cannot be measured.
    Pooling a rise into its whole 8-minute phase averages the scale-up away.

    Cut for BOTH models even though only one rises per phase: identical stage
    boundaries mean one stage index means one window for both, and the opening
    of a falling model's phase is a useful control rather than a cost.
    """
    stages = []
    prev = None
    for start, end, ra, rb in schedule:
        # Cut only a phase some model RISES into. The lead-in and the both-low
        # overlap bands have nothing to measure a rise window of, and splitting
        # them would only spend stages.
        rises = prev is not None and (ra > prev[0] or rb > prev[1])
        prev = (ra, rb)
        if rises and end - start > rise_window > 0:
            stages.append((start, start + rise_window, ra, rb))
            stages.append((start + rise_window, end, ra, rb))
        else:
            stages.append((start, end, ra, rb))
    return stages


def stages_for(stages, role):
    """One model's ladder: (rate, duration) per stage."""
    idx = 2 if role == "a" else 3
    return [(st[idx], st[1] - st[0]) for st in stages]


def split_input(input_tokens):
    """(system_prompt_len, question_len) summing to input_tokens.

    For `--data shared_prefix` only. Three quarters shared, one quarter unique.
    An earlier docstring here said the shared part is "the mechanism this
    scenario leans on to spread load across replicas". It is the opposite:
    prefix caching CONCENTRATES load on whichever replica cached the prefix
    first (see the module docstring for the measurement), which is why this
    dataset is no longer the default.
    """
    system = (input_tokens * 3) // 4
    question = input_tokens - system
    return system, question


def planned_requests(stages, role):
    """How many arrivals this role's ladder issues, in expectation."""
    return sum(rate * duration for rate, duration in stages_for(stages, role))


def render_data(args, stages, role, seed):
    """The `data:` block. Synthetic by default; see the module docstring."""
    lines = []
    if args.data == "synthetic":
        # total_count is MANDATORY and indexed without a modulo: inference-perf
        # draws its per-request lengths from arrays of exactly this many
        # entries, so a run that issues more requests than this dies with an
        # IndexError partway through its ladder. Sized at twice the planned
        # arrivals plus a margin -- Poisson overshoot and a driver that keeps
        # issuing while the last stage drains are both covered.
        total = int(2 * planned_requests(stages, role)) + 1000
        lines.append("  type: synthetic")
        for name, n in (("input_distribution", args.input_tokens),
                        ("output_distribution", args.output_tokens)):
            # Fixed lengths. The scenario prices both arms at INPUT_TOKENS in
            # and OUTPUT_TOKENS out; a distribution would make "1000 tokens"
            # mean something different in every stage.
            lines.append("  %s:" % name)
            lines.append("    min: %d" % n)
            lines.append("    max: %d" % n)
            lines.append("    mean: %d" % n)
            lines.append("    std_dev: 0")
            lines.append("    total_count: %d" % total)
        return lines
    system_len, question_len = split_input(args.input_tokens)
    lines.append("  type: shared_prefix")
    lines.append("  shared_prefix:")
    lines.append("    num_groups: %d" % args.prefix_groups)
    lines.append("    num_prompts_per_group: %d" % args.prompts_per_group)
    lines.append("    system_prompt_len: %d" % system_len)
    lines.append("    question_len: %d" % question_len)
    lines.append("    output_len: %d" % args.output_tokens)
    lines.append("    enable_multi_turn_chat: false")
    lines.append("    seed: %d" % seed)
    return lines


def yaml_quote(s):
    """Single-quoted YAML scalar. Model ids and URLs only -- no newlines."""
    return "'" + str(s).replace("'", "''") + "'"


def render_profile(args, stages, role):
    model = args.model_a if role == "a" else args.model_b
    base_url = args.endpoint_a if role == "a" else args.endpoint_b
    # Distinct seeds per role so the two models do not receive the same
    # question text at the same instant; derived from the one seed so the run
    # stays reproducible from a single knob.
    seed = args.seed + (0 if role == "a" else 1)

    lines = []
    lines.append("# GENERATED by hack/benchmark/two_model_profile.py -- do not edit.")
    lines.append("# role=%s model=%s" % (role, model))
    lines.append("load:")
    # Poisson, not constant: a constant generator lands arrivals on a grid, and
    # a fleet that is scaling has a very different queue against a grid than
    # against the bursty arrivals it actually sees.
    lines.append("  type: poisson")
    # ZERO, and it is not a detail. `interval` is the SLEEP BETWEEN STAGES --
    # inference-perf's load generator does `if self.stageInterval: await
    # sleep(self.stageInterval)` after each stage drains -- not a metrics
    # interval, which is what the name suggests and what the shipped guide
    # profiles' `interval: 30.0` reads as.
    #
    # Measured at 30: exactly 30s of ZERO load between every stage, including
    # immediately before each rise stage. Queues drain and the autoscaler sees
    # an idle fleet in the seconds before the burst this scenario exists to
    # measure, which understates every scale-up -- and on the default schedule
    # it is 240s of silence in a 2040s run. Stages must run back to back,
    # because a phase boundary is a change of rate, not a pause.
    lines.append("  interval: 0")
    lines.append("  base_seed: %d" % seed)
    lines.append("  request_timeout: %.1f" % float(args.request_timeout))
    # The driver must never be the bottleneck being measured. Sized against the
    # worst phase: high rate x request timeout is the most requests that can be
    # in flight at once if the cluster stops answering entirely.
    lines.append("  num_workers: %d" % args.workers)
    lines.append("  worker_max_concurrency: %d" % args.max_concurrency)
    lines.append("  stages:")
    for rate, duration in stages_for(stages, role):
        lines.append("  - rate: %g" % rate)
        lines.append("    duration: %d" % duration)
    lines.append("api:")
    lines.append("  type: completion")
    # Required: TTFT is only observable on a streamed response.
    lines.append("  streaming: true")
    lines.append("server:")
    lines.append("  type: vllm")
    lines.append("  model_name: %s" % yaml_quote(model))
    # No /v1 here: the client appends the route itself, so the base_url is the
    # gateway plus this stack's path prefix and nothing more.
    lines.append("  base_url: %s" % yaml_quote(base_url))
    # Without ignore_eos the output length is whatever the model decides, and
    # the two models decide differently -- so the arms would differ in work
    # done per request, not just in when it arrived.
    lines.append("  ignore_eos: true")
    lines.append("tokenizer:")
    lines.append("  pretrained_model_name_or_path: %s" % yaml_quote(model))
    # The synthetic generator is seeded from `load.base_seed` (inference-perf
    # passes config.load.base_seed to it), so the per-role seed above already
    # gives the two models different prompt streams.
    lines.append("data:")
    lines.extend(render_data(args, stages, role, seed))
    lines.append("report:")
    lines.append("  request_lifecycle:")
    lines.append("    summary: true")
    lines.append("    per_stage: true")
    # OFF. The per-request record stores `response_metrics.response_chunks` --
    # the raw SSE text of every chunk of every response -- and at 500 output
    # tokens that file reached 1.2 GB for an ELEVEN MINUTE run. `kubectl cp` is
    # exec+tar and truncated it, so the arm was lost at the collection step
    # after all its accelerators had been spent.
    #
    # Nothing is lost by turning it off. It carries no token timestamps (that is
    # why the rise windows are stages), and the counts and failure breakdown the
    # report needs are in `successes.count` and `failures.by_label` of the stage
    # files, which are 7 KB each.
    lines.append("    per_request: false")
    lines.append("storage:")
    lines.append("  local_storage:")
    lines.append("    path: %s" % yaml_quote("%s/%s" % (args.results_root.rstrip("/"), role)))
    return "\n".join(lines) + "\n"


def default_workers(high_rps, request_timeout):
    """Enough workers that the driver cannot be the queue.

    An open-loop generator only stays open-loop while it has somewhere to put
    the next arrival. At `high_rps` with responses taking up to `request_timeout`
    the worst-case in-flight count is their product; below that the generator
    starts delaying arrivals and reporting the delay as the cluster's latency.
    """
    return max(4, min(32, int(high_rps * 2)))


def build_parser():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--emit", choices=("profile", "schedule"), required=True)
    p.add_argument("--role", choices=("a", "b"),
                   help="which model's profile to render (required with --emit profile)")
    p.add_argument("--model-a", default="A")
    p.add_argument("--model-b", default="B")
    p.add_argument("--endpoint-a", default="")
    p.add_argument("--endpoint-b", default="")
    p.add_argument("--phase-seconds", type=int, default=480)
    p.add_argument("--cycles", type=int, default=2)
    p.add_argument("--lead-in", type=int, default=120)
    p.add_argument("--low-rps", type=float, default=3)
    p.add_argument("--high-rps", type=float, default=9,
                   help="model A's burst rate")
    p.add_argument("--high-rps-b", type=float, default=None,
                   help="model B's burst rate; defaults to --high-rps. The two "
                        "models rarely have the same per-replica capacity")
    p.add_argument("--input-tokens", type=int, default=1000)
    p.add_argument("--output-tokens", type=int, default=500)
    p.add_argument("--overlap", type=int, default=90,
                   help="seconds of BOTH models at the low rate between phases, "
                        "so their bursts cannot run into each other when the two "
                        "drain at different speeds")
    p.add_argument("--rise-window", type=int, default=240,
                   help="seconds at the start of each phase measured as its own "
                        "stage; the harness reports TTFT per stage and nothing "
                        "finer, so this is what a rise window can be")
    p.add_argument("--data", choices=("synthetic", "shared_prefix"), default="synthetic",
                   help="synthetic: every prompt a fresh random slice of the corpus, "
                        "no shared prefix (the default -- see the module docstring "
                        "for why). shared_prefix: the dataset that pinned each "
                        "model to one replica; kept to reproduce that")
    p.add_argument("--prefix-groups", type=int, default=32,
                   help="shared_prefix only: distinct shared prefixes")
    p.add_argument("--prompts-per-group", type=int, default=64,
                   help="shared_prefix only: distinct questions per prefix")
    p.add_argument("--request-timeout", type=float, default=300)
    p.add_argument("--seed", type=int, default=1729)
    p.add_argument("--workers", type=int, default=0,
                   help="0 picks a value from the high rate and the timeout")
    p.add_argument("--max-concurrency", type=int, default=256)
    p.add_argument("--results-root", default="/results")
    return p


def main(argv):
    args = build_parser().parse_args(argv)
    if args.emit == "profile" and not args.role:
        print("--emit profile needs --role a or --role b", file=sys.stderr)
        return 2
    if args.cycles < 1:
        print("--cycles must be at least 1: with none, neither model ever rises "
              "and there is nothing for a warm pool to be measured against.",
              file=sys.stderr)
        return 2
    if args.high_rps <= args.low_rps or (args.high_rps_b is not None
                                        and args.high_rps_b <= args.low_rps):
        print("--high-rps and --high-rps-b must exceed --low-rps: the scenario is a "
              "burst, and with a flat rate no scale-up happens in either arm.",
              file=sys.stderr)
        return 2
    if args.rise_window >= args.phase_seconds:
        print("--rise-window (%d) must be shorter than --phase-seconds (%d): a phase that "
              "is not cut has no rise stage, and this harness reports latency per stage "
              "only -- so every scale-up would be averaged into the whole phase and "
              "reported as steady state."
              % (args.rise_window, args.phase_seconds), file=sys.stderr)
        return 2
    if args.data == "shared_prefix" and args.prefix_groups < 2:
        print("--prefix-groups must be at least 2: a single shared prefix makes "
              "the router's prefix-cache scorer pin every request to whichever "
              "replica cached it first, and the run measures a one-replica fleet.",
              file=sys.stderr)
        return 2
    if args.workers <= 0:
        args.workers = default_workers(args.high_rps, args.request_timeout)

    schedule = build_schedule(args.phase_seconds, args.cycles,
                              args.low_rps, args.high_rps, args.lead_in,
                              args.overlap, args.high_rps_b)
    stages = stage_map(schedule, args.rise_window)
    if args.emit == "schedule":
        json.dump(schedule_json(stages), sys.stdout, indent=2)
        sys.stdout.write("\n")
        return 0
    sys.stdout.write(render_profile(args, stages, args.role))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
