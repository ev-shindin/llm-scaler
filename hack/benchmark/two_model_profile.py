#!/usr/bin/env python3
"""
two_model_profile.py -- render the inference-perf profiles that drive the
two-model anti-phase run, plus the phase table the report buckets against.

Load is generated by inference-perf, the llm-d benchmark harness's own load
generator, rather than by a bespoke client. That is not a cosmetic choice:

  * The schedule is a first-class object in the harness (`load.stages`), so
    anti-phase is expressed by giving the two models MIRRORED ladders over the
    same boundaries rather than by a loop that has to be trusted to keep time.
  * The harness tokenizes with the model's OWN tokenizer, so `input_tokens`
    means input tokens. A hand-rolled generator that counts words is off by
    whatever the tokenizer does, differently for each of the two models -- and
    this scenario compares two models.
  * It reports its own scheduling delay (`load_summary.schedule_delay`), which
    is exactly the quantity that decides whether the driver, rather than the
    cluster, produced the latency being compared. Self-reported by the thing
    that would be at fault.

One profile per model, written from one schedule so the two cannot drift:
`--emit schedule` prints that schedule as JSON for the report's meta, and
`--emit profile --role a|b` prints the YAML for one side of it.

The phases are the harness's STAGES, one for one. A stage is time-boxed, so
both models cross every boundary together as long as they start together --
which the Job's start barrier, not this file, is responsible for.
"""

import argparse
import json
import sys


def build_schedule(phase_seconds, cycles, low_rps, high_rps, lead_in):
    """Anti-phase square wave: A low->high->low..., B high->low->high...

    Identical to the schedule the previous bespoke loader built, deliberately:
    the report's rise windows, the meta signature and the runbook's phase table
    all key on this shape, and changing the load generator is already enough of
    a change to be comparing.
    """
    phases = []
    t = 0
    if lead_in > 0:
        # Both models at the LOW rate first. Without it the run starts at the
        # instant of a burst and every arm measures a cold stack rather than a
        # scale-up: the models have never served a request, the pool has never
        # been asked for anything, and the first burst pays a first-request
        # penalty that has nothing to do with the pool.
        phases.append((t, t + lead_in, low_rps, low_rps))
        t += lead_in
    for _ in range(cycles):
        phases.append((t, t + phase_seconds, low_rps, high_rps))
        t += phase_seconds
        phases.append((t, t + phase_seconds, high_rps, low_rps))
        t += phase_seconds
    return phases


def schedule_json(schedule):
    return [{"start": s, "end": e, "rate_a": ra, "rate_b": rb}
            for s, e, ra, rb in schedule]


def stages_for(schedule, role):
    """The harness stage ladder for one model: (rate, duration) per phase."""
    idx = 2 if role == "a" else 3
    return [(ph[idx], ph[1] - ph[0]) for ph in schedule]


def split_input(input_tokens):
    """(system_prompt_len, question_len) summing to input_tokens.

    Three quarters shared, one quarter unique. The shared part has to be long
    enough that caching it is worth a router's while -- that is the whole
    mechanism this scenario leans on to spread load across replicas -- and the
    unique part long enough that two requests in the same group are not the
    same request.
    """
    system = (input_tokens * 3) // 4
    question = input_tokens - system
    return system, question


def yaml_quote(s):
    """Single-quoted YAML scalar. Model ids and URLs only -- no newlines."""
    return "'" + str(s).replace("'", "''") + "'"


def render_profile(args, schedule, role):
    model = args.model_a if role == "a" else args.model_b
    base_url = args.endpoint_a if role == "a" else args.endpoint_b
    system_len, question_len = split_input(args.input_tokens)
    # Distinct seeds per role so the two models do not receive the same
    # question text at the same instant; derived from the one seed so the run
    # stays reproducible from a single knob.
    seed = args.seed + (0 if role == "a" else 1)

    lines = []
    lines.append("# GENERATED by hack/benchmark/two_model_profile.py -- do not edit.")
    lines.append("# role=%s model=%s" % (role, model))
    lines.append("load:")
    # Poisson, not constant: a constant generator lands arrivals on a grid, and
    # a fleet that is scaling has a very different queue against a grid than
    # against the bursty arrivals it actually sees.
    lines.append("  type: poisson")
    # The generator's own metrics interval, NOT the stage length -- stages carry
    # their own durations, and the phase boundaries come from those. Kept well
    # below a phase so a phase is described by several points rather than one.
    lines.append("  interval: %d" % max(1, min(30, args.phase_seconds)))
    lines.append("  base_seed: %d" % seed)
    lines.append("  request_timeout: %.1f" % float(args.request_timeout))
    # The driver must never be the bottleneck being measured. Sized against the
    # worst phase: high rate x request timeout is the most requests that can be
    # in flight at once if the cluster stops answering entirely.
    lines.append("  num_workers: %d" % args.workers)
    lines.append("  worker_max_concurrency: %d" % args.max_concurrency)
    lines.append("  stages:")
    for rate, duration in stages_for(schedule, role):
        lines.append("  - rate: %g" % rate)
        lines.append("    duration: %d" % duration)
    lines.append("api:")
    lines.append("  type: completion")
    # Required: TTFT is only observable on a streamed response.
    lines.append("  streaming: true")
    lines.append("server:")
    lines.append("  type: vllm")
    lines.append("  model_name: %s" % yaml_quote(model))
    # No /v1 here: the client appends the route itself, so the base_url is the
    # gateway plus this stack's path prefix and nothing more.
    lines.append("  base_url: %s" % yaml_quote(base_url))
    # Without ignore_eos the output length is whatever the model decides, and
    # the two models decide differently -- so the arms would differ in work
    # done per request, not just in when it arrived.
    lines.append("  ignore_eos: true")
    lines.append("tokenizer:")
    lines.append("  pretrained_model_name_or_path: %s" % yaml_quote(model))
    lines.append("data:")
    lines.append("  type: shared_prefix")
    lines.append("  shared_prefix:")
    lines.append("    num_groups: %d" % args.prefix_groups)
    lines.append("    num_prompts_per_group: %d" % args.prompts_per_group)
    lines.append("    system_prompt_len: %d" % system_len)
    lines.append("    question_len: %d" % question_len)
    lines.append("    output_len: %d" % args.output_tokens)
    lines.append("    enable_multi_turn_chat: false")
    lines.append("    seed: %d" % seed)
    lines.append("report:")
    lines.append("  request_lifecycle:")
    lines.append("    summary: true")
    lines.append("    per_stage: true")
    # The per-request file is what the report reads: percentiles over a whole
    # run cannot be re-cut into rise windows after the fact.
    lines.append("    per_request: true")
    lines.append("storage:")
    lines.append("  local_storage:")
    lines.append("    path: %s" % yaml_quote("%s/%s" % (args.results_root.rstrip("/"), role)))
    return "\n".join(lines) + "\n"


def default_workers(high_rps, request_timeout):
    """Enough workers that the driver cannot be the queue.

    An open-loop generator only stays open-loop while it has somewhere to put
    the next arrival. At `high_rps` with responses taking up to `request_timeout`
    the worst-case in-flight count is their product; below that the generator
    starts delaying arrivals and reporting the delay as the cluster's latency.
    """
    return max(4, min(32, int(high_rps * 2)))


def build_parser():
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--emit", choices=("profile", "schedule"), required=True)
    p.add_argument("--role", choices=("a", "b"),
                   help="which model's profile to render (required with --emit profile)")
    p.add_argument("--model-a", default="A")
    p.add_argument("--model-b", default="B")
    p.add_argument("--endpoint-a", default="")
    p.add_argument("--endpoint-b", default="")
    p.add_argument("--phase-seconds", type=int, default=480)
    p.add_argument("--cycles", type=int, default=2)
    p.add_argument("--lead-in", type=int, default=120)
    p.add_argument("--low-rps", type=float, default=3)
    p.add_argument("--high-rps", type=float, default=9)
    p.add_argument("--input-tokens", type=int, default=1000)
    p.add_argument("--output-tokens", type=int, default=500)
    p.add_argument("--prefix-groups", type=int, default=32)
    p.add_argument("--prompts-per-group", type=int, default=64)
    p.add_argument("--request-timeout", type=float, default=300)
    p.add_argument("--seed", type=int, default=1729)
    p.add_argument("--workers", type=int, default=0,
                   help="0 picks a value from the high rate and the timeout")
    p.add_argument("--max-concurrency", type=int, default=256)
    p.add_argument("--results-root", default="/results")
    return p


def main(argv):
    args = build_parser().parse_args(argv)
    if args.emit == "profile" and not args.role:
        print("--emit profile needs --role a or --role b", file=sys.stderr)
        return 2
    if args.cycles < 1:
        print("--cycles must be at least 1: with none, neither model ever rises "
              "and there is nothing for a warm pool to be measured against.",
              file=sys.stderr)
        return 2
    if args.high_rps <= args.low_rps:
        print("--high-rps must exceed --low-rps: the scenario is a burst, and "
              "with a flat rate no scale-up happens in either arm.", file=sys.stderr)
        return 2
    if args.prefix_groups < 2:
        print("--prefix-groups must be at least 2: a single shared prefix makes "
              "the router's prefix-cache scorer pin every request to whichever "
              "replica cached it first, and the run measures a one-replica fleet.",
              file=sys.stderr)
        return 2
    if args.workers <= 0:
        args.workers = default_workers(args.high_rps, args.request_timeout)

    schedule = build_schedule(args.phase_seconds, args.cycles,
                              args.low_rps, args.high_rps, args.lead_in)
    if args.emit == "schedule":
        json.dump(schedule_json(schedule), sys.stdout, indent=2)
        sys.stdout.write("\n")
        return 0
    sys.stdout.write(render_profile(args, schedule, args.role))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
